def patch_server() -> None:
    if not SERVER.exists():
        raise SystemExit("server_session.py not found. Run this from backend directory.")
    backup(SERVER)
    s = SERVER.read_text(encoding="utf-8")

    # Replace identity functions.
    pattern = re.compile(
        r"def _sanitize_user_key\(key: str\) -> str:\n.*?def _derive_user_key\(req: Request, body: Dict\[str, Any\]\) -> str:\n.*?return _sanitize_user_key\(f\"anon_ip:\{ip\}\"\)\n+",
        re.DOTALL,
    )
    s2, n = pattern.subn(IDENTITY_REPLACEMENT, s, count=1)
    if n != 1:
        raise SystemExit("Could not replace _sanitize_user_key/_derive_user_key block. Check server_session.py around memory config area.")
    s = s2
    print("patched server_session.py identity resolver")

    # Add status/debug routes before vector memory APIs.
    anchor = "# -----------------------------\n# ✅ Vector memory APIs\n# -----------------------------\n"
    if "/api/brain/memory/status" not in s:
        if anchor not in s:
            raise SystemExit("Could not find Vector memory APIs anchor for status routes")
        s = s.replace(anchor, STATUS_ROUTES + anchor, 1)
        print("added commercial memory status/debug routes")
    else:
        print("status/debug routes already present")

    # Do not trust raw client_id as an override in /tools/search_memory.
    old = 'user_key = _sanitize_user_key(client_id or _derive_user_key(req, body))'
    new = 'user_key = _derive_user_key(req, body)'
    if old in s:
        s = s.replace(old, new, 1)
        print("patched /tools/search_memory identity source")
    else:
        print("/tools/search_memory identity source already patched or not found")

    SERVER.write_text(s, encoding="utf-8")


def main() -> None:
    patch_auth()
    patch_server()
    print("\nDONE. Next:")
    print("  1) cp memory_identity.py backend/")
    print("  2) restart server")
    print("  3) run: python test_memory_isolation.py")


if __name__ == "__main__":
    main()
